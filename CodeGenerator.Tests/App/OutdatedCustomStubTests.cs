using System.Linq;
using AppScaffolding;
using AppScaffolding.Incremental;
using AppScaffolding.Targets;
using CodeGenerationEngine.Core;
using CodeGenerationEngine.Models;
using DomainDiscovery.Model;
using Microsoft.CodeAnalysis;

namespace CodeGenerator.Tests.App;

/// <summary>
/// This branch's own regression, and the report that owns it: phase 2 changed the emitted
/// hand-written hook from <c>partial void ValidateCustom(T item, List&lt;string&gt; errors)</c> to
/// <c>private static partial void ValidateCustom(T item, List&lt;ValidationError&gt; errors)</c>,
/// while <c>&lt;Model&gt;Validator.Custom.cs</c> is written once and never overwritten. An app
/// generated by an earlier version therefore keeps the old declaration beside a freshly
/// regenerated <c>.Generated.cs</c>, and the pair does not compile.
/// </summary>
/// <remarks>
/// The existing coverage was
/// <c>ValidatorScaffoldingTests.A_hand_edited_custom_validator_survives_regeneration</c>, which
/// writes <c>"// MY OWN RULES"</c> as the stub BODY — so it passes while proving nothing about the
/// SIGNATURE, which is the half that broke. Every test here asks about the signature, and
/// <see cref="TheOldStubAndTheRegeneratedHalfDoNotCompile"/> compiles the pair rather than
/// describing it, because a substring assertion over emitted source is how this branch hid real
/// breakage once already.
/// </remarks>
[TestClass]
public class OutdatedCustomStubTests
{
    private const string Root = "Shop";

    /// <summary>One entity, one string field: enough for a real Validation/ folder without
    /// dragging a foreign key into a test about a declaration.</summary>
    private static CandidateDomainModel OneEntity()
    {
        var model = new CandidateDomainModel();
        model.Entities.Add(new CandidateEntity
        {
            Name = "Customer",
            Fields = { new CandidateField { Name = "Surname", Type = "string" } },
        });
        return model;
    }

    /// <summary>
    /// Turns a stub this version wrote into the stub the previous version wrote, by changing the
    /// DECLARATION and nothing else.
    /// </summary>
    /// <remarks>
    /// Derived from the real current stub rather than hand-written, so it cannot drift out of step
    /// with what <see cref="ValidatorTemplate.CustomStub"/> emits, and so the body it leaves behind
    /// is demonstrably the untouched one the generator wrote — the case
    /// <c>A_hand_edited_custom_validator_survives_regeneration</c> cannot reach.
    /// </remarks>
    private static string Downgrade(string stub, string className)
    {
        var downgraded = stub.Replace(
            ValidatorTemplate.CustomHookDeclaration(className),
            $"partial void ValidateCustom({className} item, List<string> errors)",
            StringComparison.Ordinal);

        Assert.AreNotEqual(stub, downgraded, "the current declaration was not found in the stub");

        return downgraded;
    }

    [TestMethod]
    public void TheStubThisVersionWritesIsNotReportedAsOutdated()
    {
        // A stub falsely accused sends someone editing a file that was already right, so this is
        // the assertion that has to hold first.
        Assert.IsFalse(ValidatorTemplate.HasOutdatedCustomHook(
            ValidatorTemplate.CustomStub(Root, "Customer")));
    }

    [TestMethod]
    public void AnUntouchedStubFromBeforeThePipelineIsOutdated()
    {
        var old = Downgrade(ValidatorTemplate.CustomStub(Root, "Customer"), "Customer");

        Assert.IsTrue(ValidatorTemplate.HasOutdatedCustomHook(old));
    }

    /// <summary>The body is not the question — which is the whole gap in the existing test.</summary>
    [TestMethod]
    public void TheBodyDoesNotDecideIt()
    {
        var current = ValidatorTemplate.CustomStub(Root, "Customer")
            .Replace(
                "    {\r\n    }",
                "    {\r\n        // MY OWN RULES\r\n    }",
                StringComparison.Ordinal);

        Assert.IsFalse(
            ValidatorTemplate.HasOutdatedCustomHook(current),
            "a hand-edited body under the CURRENT declaration is fine");

        Assert.IsTrue(
            ValidatorTemplate.HasOutdatedCustomHook(Downgrade(current, "Customer")),
            "the same body under the OLD declaration is not");
    }

    /// <summary>
    /// The reason the report exists, evidenced rather than described: the exact pair a regenerate
    /// leaves on disk, compiled.
    /// </summary>
    /// <remarks>
    /// Compiled as separate syntax trees through <see cref="Compiler.CompileSources"/> — never a
    /// concatenation, and never a substring assertion — because a partial-method mismatch is
    /// invisible to both. The two diagnostics are named individually: CS0759 is the kept stub
    /// implementing a declaration that no longer exists, CS8795 is the regenerated half declaring
    /// one nothing implements, and a fix that silenced only one would leave the folder just as
    /// broken.
    /// </remarks>
    [TestMethod]
    public void TheOldStubAndTheRegeneratedHalfDoNotCompile()
    {
        var definition = new ClassDefinition { Name = "Customer" };
        definition.Properties.Add(new PropertyDefinition { Name = "Id", Type = "int" });

        var surname = new PropertyDefinition { Name = "Surname", Type = "string" };
        surname.Rules.Add(new PropertyRule { Name = "required" });
        definition.Properties.Add(surname);

        var models = """
namespace Shop.Models;

public partial class Customer
{
    public int Id { get; set; }
    public string Surname { get; set; } = string.Empty;
}
""";

        var result = Compiler.CompileSources(new (string Path, string Code)[]
        {
            ("Validation/ValidationContext.cs", ValidationContextTemplate.Source(Root)),
            ("Validation/IValidator.cs", ValidatorTemplate.ValidatorInterface(Root)),
            ("Validation/IEntityLookup.cs", ValidatorTemplate.EntityLookupInterface(Root)),
            ("Validation/ValidationPipeline.cs", ValidationPipelineTemplate.Source(Root)),
            ("Validation/Permissions.cs", PermissionsTemplate.Source(Root, ["Customer"])),
            ("Models/Customer.cs", models),
            ("Validation/CustomerValidator.Generated.cs",
                ValidatorTemplate.Generated(Root, definition, [])),
            ("Validation/CustomerValidator.Custom.cs",
                Downgrade(ValidatorTemplate.CustomStub(Root, "Customer"), "Customer")),
        });

        var ids = result.Diagnostics
            .Where(d => d.Severity == DiagnosticSeverity.Error)
            .Select(d => d.Id)
            .ToList();

        Assert.IsFalse(result.Success, "the mismatched pair should NOT compile");
        CollectionAssert.Contains(
            ids, "CS0759", "the kept stub implements a declaration that is gone");
        CollectionAssert.Contains(
            ids, "CS8795", "the regenerated half declares one nothing implements");
    }

    /// <summary>
    /// The whole-scaffold half: regenerate over an app whose stub predates the pipeline, and the
    /// run says so, names the file and gives the line to put in it.
    /// </summary>
    [TestMethod]
    public void RegeneratingOverAStubFromBeforeThePipelineReportsIt()
    {
        var workspace = NewWorkspace();
        try
        {
            var model = OneEntity();
            var first = Scaffold(model, workspace);

            var stubPath = Path.Combine(
                first.ProjectPath, "Validation", "CustomerValidator.Custom.cs");
            var written = File.ReadAllText(stubPath);

            // The generator's own body, untouched. Only the declaration goes back a version.
            File.WriteAllText(stubPath, Downgrade(written, "Customer"));

            var again = Scaffold(model, workspace);

            Assert.HasCount(1, again.OutdatedValidatorStubs);

            var report = again.OutdatedValidatorStubs[0];
            StringAssert.Contains(report, "Validation/CustomerValidator.Custom.cs");
            StringAssert.Contains(report, ValidatorTemplate.CustomHookDeclaration("Customer"));

            // Reported, not rewritten: a rewritten declaration over a hand-written body fails
            // CS1503 instead, and a half-migrated file is the worse outcome.
            Assert.AreEqual(Downgrade(written, "Customer"), File.ReadAllText(stubPath));

            // And on the surface a failure would have shown it, so no reader of the result loses it.
            StringAssert.Contains(again.Message, "Validation/CustomerValidator.Custom.cs");
        }
        finally
        {
            Cleanup(workspace);
        }
    }

    /// <summary>A regenerate of an app THIS version wrote reports nothing — the guard on the
    /// report being about the old shape and not about write-once-ness.</summary>
    [TestMethod]
    public void RegeneratingOverACurrentStubReportsNothing()
    {
        var workspace = NewWorkspace();
        try
        {
            var model = OneEntity();
            Scaffold(model, workspace);

            var again = Scaffold(model, workspace);

            Assert.IsEmpty(again.OutdatedValidatorStubs);
        }
        finally
        {
            Cleanup(workspace);
        }
    }

    /// <summary>
    /// The add-to-an-existing-app half, which skips the same file for the same reason
    /// (<c>IncrementalFiles.ShouldCopy</c>) and so owes the same report.
    /// </summary>
    /// <remarks>
    /// Under <c>C:\cg-t</c> rather than the temp path: a GUID plus a project name plus
    /// <c>Models\Whatever.cs</c> blows MAX_PATH, and the tell is MSB3030 claiming a file is missing
    /// that is plainly there.
    /// </remarks>
    [TestMethod]
    public void AnAddOverAStubFromBeforeThePipelineReportsIt()
    {
        var root = Path.Combine(@"C:\cg-t", Guid.NewGuid().ToString("N")[..8]);
        Directory.CreateDirectory(root);

        try
        {
            var target = new ClassLibraryTarget();

            var first = new AppScaffolder().Scaffold(
                ScaffoldRequest.For(OneEntity(), Root, root, target));
            Assert.IsTrue(first.Success, "scaffold failed: " + first.Message);

            var stubPath = Path.Combine(
                first.ProjectPath, "Validation", "CustomerValidator.Custom.cs");
            File.WriteAllText(stubPath, Downgrade(File.ReadAllText(stubPath), "Customer"));

            var grown = OneEntity();
            grown.Entities.Add(new CandidateEntity { Name = "Supplier" });

            var added = IncrementalScaffolder.Add(
                ScaffoldRequest.For(grown, Root, root, target), ["Supplier"]);

            Assert.IsTrue(added.Success, added.Message);
            Assert.HasCount(1, added.OutdatedValidatorStubs);

            var report = added.OutdatedValidatorStubs[0];
            StringAssert.Contains(report, "CustomerValidator.Custom.cs");
            StringAssert.Contains(report, ValidatorTemplate.CustomHookDeclaration("Customer"));

            // The new class's own stub is brand new and in the current shape, so it is not named.
            Assert.DoesNotContain("Supplier", report);
        }
        finally
        {
            Cleanup(root);
        }
    }

    private static string NewWorkspace()
    {
        var path = Path.Combine(Path.GetTempPath(), "scg-oldstub-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(path);
        return path;
    }

    /// <summary>ClassLibraryTarget needs no WPF or ASP.NET tooling to create.</summary>
    private static ScaffoldResult Scaffold(CandidateDomainModel model, string workspace)
    {
        var result = new AppScaffolder().Scaffold(
            model, Root, workspace, new ClassLibraryTarget());

        Assert.IsTrue(result.Success, "scaffold failed: " + result.Message);

        return result;
    }

    private static void Cleanup(string folder)
    {
        try
        {
            Directory.Delete(folder, recursive: true);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
        }
    }
}
